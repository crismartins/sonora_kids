const SLUG_OVERRIDES: Record<string, string> = {
  "vovó": "vovo-a",
  "vovô": "vovo-o",
};

export function pecTitleSlug(title: string) {
  const lower = title.trim().toLocaleLowerCase("pt-BR");
  const override = SLUG_OVERRIDES[lower];
  if (override) return override;
  return lower
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");
}

export function imageForPecTitle(title: string): ImageSourcePropType | undefined {
  return PEC_LOCAL_IMAGES[pecTitleSlug(title)];
}
